"""Synchronize scalar EF types/lengths with the canonical SQL scripts (no migrations)."""
from pathlib import Path
import re

root=Path(__file__).resolve().parents[2]
sql='\n'.join(p.read_text(encoding='utf-8') for p in sorted((root/'database').glob('0[1-9]_*.sql')))
tables=dict(re.findall(r'CREATE TABLE\s+(\w+\.\w+)\s*\((.*?)\)\s*;\s*GO',sql,re.S))
entities='\n'.join(p.read_text(encoding='utf-8') for p in (root/'backend/src/GymFlow.Domain/Entities').glob('*.cs'))
properties={name:set(re.findall(r'public\s+[\w?\[\]]+\s+(\w+)\s*\{\s*get;',body)) for name,body in re.findall(r'public sealed class (\w+)[^{]*\{(.*?)(?=\n\}|\Z)',entities,re.S)}
context=(root/'backend/src/GymFlow.Infrastructure/Persistence/GymFlowDbContext.cs').read_text(encoding='utf-8')
lines=['// Generated by scripts/generate_sql_mappings.py from canonical database scripts.',
       'using GymFlow.Domain.Entities;', 'using Microsoft.EntityFrameworkCore;',
       '', 'namespace GymFlow.Infrastructure.Persistence;', '',
       'internal static class SqlColumnMappings', '{', '    public static void Apply(ModelBuilder modelBuilder)', '    {']
for entity,body in re.findall(r'modelBuilder.Entity<(\w+)>\(b =>\s*\{(.*?)\}\);',context,re.S):
    table=re.search(r'b.ToTable\("(\w+)", "(\w+)"',body)
    if not table:
        continue
    for name,typ,size in re.findall(r'^\s*(\w+)\s+(N?VARCHAR|CHAR|DATETIME2|VARBINARY)\((MAX|\d+)\)',tables[table[2]+'.'+table[1]],re.M):
        if name not in properties.get(entity,set()):
            continue
        config=f'        modelBuilder.Entity<{entity}>().Property(x => x.{name}).HasColumnType("{typ.lower()}({size.lower()})")'
        if typ in ('VARCHAR','NVARCHAR','CHAR'):
            config+=f'.IsUnicode({str(typ.startswith("N")).lower()})'
            if size!='MAX':
                config+=f'.HasMaxLength({size})'
        lines.append(config+';')
lines+=['    }','}']
(root/'backend/src/GymFlow.Infrastructure/Persistence/SqlColumnMappings.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Generated {len(lines)-12} scalar mappings')
